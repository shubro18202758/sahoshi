"""The offline place gazetteer (contract X19): load it (places only), normalise text, find the places a text names.

``scripts/data/osint_gazetteer.json``, generated by ``scripts/gen_osint_gazetteer.py`` (ODbL-attributed)::

    {meta: {generated_at, source, licence: "© OpenStreetMap contributors, ODbL 1.0", entries},
     entries: [{gaz_id, canonical_name, feature_type: road|junction|neighbourhood|landmark|admin|poi,
                surface_forms[], lon, lat, junction_id|null, segment_id|null, importance, source, lang_primary}]}

* **Path rules** (:func:`resolve_path`): the argument, then ``$OSINT_GAZETTEER_PATH``, then the repo's
  ``scripts/data/osint_gazetteer.json`` found by walking up from this file, then the image path
  ``/repo/VVIP/scripts/data/osint_gazetteer.json``.
* **Places only.** The load-time check refuses an entry (or a ``meta``) with any key outside the X19 field list, so
  no person, author, handle or free-form field can ride along; it also checks every value's type and range.
* **Normal form** (:func:`norm`): NFKC, lower case, Latin diacritics folded, Unicode format characters removed,
  every run of punctuation one space (Bengali and Devanagari letters and vowel signs kept), and a split road code
  joined ("NH-147" → ``nh147``). Surface forms are matched in this form on token boundaries.
* **Longest-match index**: a token trie over every surface form. :meth:`Gazetteer.match` returns the PoC's greedy
  selection: longer forms first, every non-overlapping occurrence. A single generic word ("road", "circle") or a
  form of fewer than 3 characters is never indexed (the PoC's ``GENERIC_STOPWORDS`` guard).
* **Protect-set** (:attr:`Gazetteer.protect_set`): every normalised surface form, canonical name and parenthesised
  part of a canonical name — the places OS-2's redactor must never mistake for a person. Whole phrases only: a
  sub-phrase ("rash behari" of "rash behari avenue") would protect a person's name, so none is added.

Loaded once per process (:func:`load` caches by path behind a lock); every structure is immutable afterwards, so a
:class:`Gazetteer` is safe to share between threads. Stdlib only.
"""

