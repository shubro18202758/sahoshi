GAZETTEER_ENV = "OSINT_GAZETTEER_PATH"
_REPO_RELATIVE = ("scripts", "data", "osint_gazetteer.json")
IMAGE_PATH = Path("/repo/VVIP/scripts/data/osint_gazetteer.json")
#: The attribution every generated gazetteer carries (``meta.licence``).
LICENCE = "© OpenStreetMap contributors, ODbL 1.0"

#: The X19 entry fields, in file order: nothing else is accepted (places only).
ENTRY_FIELDS: tuple[str, ...] = (
    "gaz_id",
    "canonical_name",
    "feature_type",
    "surface_forms",
    "lon",
    "lat",
    "junction_id",
    "segment_id",
    "importance",
    "source",
    "lang_primary",
)
#: The X19 ``meta`` fields.
META_FIELDS: tuple[str, ...] = ("generated_at", "source", "licence", "entries")
FEATURE_TYPES: tuple[str, ...] = ("road", "junction", "neighbourhood", "landmark", "admin", "poi")

#: Generic road and place words (the PoC's ``GENERIC_STOPWORDS``, plus a few civic nouns): never a toponym on their
#: own, so no single-word surface form is one, and a fuzzy window made only of them is skipped.
GENERIC_STOPWORDS: frozenset[str] = frozenset(
    {
        # the PoC's list
        "road", "rd", "cross", "roads", "circle", "cir", "bridge", "flyover", "gate", "chowk", "nagar", "marg",
        "highway", "junction", "station", "the", "near", "at", "in", "on", "to", "of", "and",
        # more generic place words (Kolkata's: crossing and "more", setu, sarani, avenue, ghat, phari, para, pally)
        "underpass", "overbridge", "pul", "lane", "street", "st", "area", "city", "zone", "ward", "district",
        "state", "society", "ramp", "service", "crossing", "more", "mor", "setu", "sarani", "avenue", "ave", "ghat",
        "phari", "para", "pally", "bypass", "chowrasta",
    }
)
#: The shortest indexable surface form (the PoC skipped forms under 3 characters).
MIN_FORM_CHARS = 3

_MAX_BYTES = 8 * 1024 * 1024
#: C0 controls, DEL and the bidi embedding/override/isolate controls: never in a place name (display spoofing)
_CONTROL = re.compile(r"[\x00-\x1f\x7f\u202a-\u202e\u2066-\u2069]")
_PARENS = re.compile(r"[()]")
_LANG = re.compile(r"^[a-z]{2,3}$")
_END = "\x00"  # trie terminal key (a token never contains NUL)


def resolve_path(
    path: str | os.PathLike[str] | None,
    *,
    env: str,
    repo_relative: Sequence[str],
    image: Path,
    anchor: Path | None = None,
) -> Path:
    """The data-file path rules shared by the gazetteer and the network: ``path``, else ``$env``, else the first
    ``<ancestor>/<repo_relative>`` walking up from ``anchor`` (this file), else ``image``. An explicit path (the
    argument or the variable) that does not exist is an error, never silently replaced by another file."""
    if path is not None:
        p = Path(path)
        if not p.is_file():
            raise FileNotFoundError(f"no such file: {p}")
        return p
    configured = os.environ.get(env)
    if configured:
        p = Path(configured)
        if not p.is_file():
            raise FileNotFoundError(f"${env} names a missing file: {p}")
        return p
    here = (anchor or Path(__file__)).resolve()
    for parent in here.parents:
        cand = parent.joinpath(*repo_relative)
        if cand.is_file():
            return cand
    if image.is_file():
        return image
    raise FileNotFoundError(f"{'/'.join(repo_relative)} not found (set ${env}, or run from the repo or the image)")


@dataclass(frozen=True, slots=True)
class GazetteerEntry:
    """One X19 place. Read it as an object (``e.gaz_id``) or as a mapping (``e["gaz_id"]``, ``dict(e)``)."""

    gaz_id: int
    canonical_name: str
    feature_type: str
    surface_forms: tuple[str, ...]
    lon: float
    lat: float
    junction_id: int | None
    segment_id: int | None
    importance: float
    source: str
    lang_primary: str

    def keys(self) -> tuple[str, ...]:
        return ENTRY_FIELDS

    def __getitem__(self, key: str) -> Any:
        if key not in ENTRY_FIELDS:
            raise KeyError(key)
        return getattr(self, key)

    def get(self, key: str, default: Any = None) -> Any:
        return getattr(self, key) if key in ENTRY_FIELDS else default

    def as_dict(self) -> dict[str, Any]:
        """The entry as its X19 JSON object (``surface_forms`` as a list)."""
        d = {k: getattr(self, k) for k in ENTRY_FIELDS}
        d["surface_forms"] = list(self.surface_forms)
        return d


class Hit(NamedTuple):
    """A surface form found in a token list: tokens ``[start, end)`` read as ``form`` (via ``"gazetteer"``, or
    ``"grammar"`` when a generic word was rewritten, "gariahat more" → ``gariahat crossing``)."""

    start: int
    end: int
    form: str
    via: str = "gazetteer"


def _is_int(v: Any) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _is_num(v: Any) -> bool:
    return (isinstance(v, (int, float)) and not isinstance(v, bool)) and math.isfinite(v)


def _text(v: Any, field: str, max_len: int) -> str:
    if not isinstance(v, str) or not v.strip() or len(v) > max_len or _CONTROL.search(v):
        raise ValueError(f"{field} must be a non-empty string of at most {max_len} characters, no control characters")
    return v


def _entry(raw: Any, index: int) -> GazetteerEntry:
    """Validate one X19 entry (places only: exactly the X19 keys, each with its type and range)."""
    where = f"entries[{index}]"
    if not isinstance(raw, Mapping):
        raise ValueError(f"{where} is not an object")
    keys = set(raw)
    extra = sorted(str(k) for k in keys - set(ENTRY_FIELDS))
    if extra:
        raise ValueError(f"{where} has keys outside the X19 field list (places only): {extra[:8]}")
    missing = sorted(set(ENTRY_FIELDS) - keys)
    if missing:
        raise ValueError(f"{where} lacks X19 fields: {missing}")
    gid = raw["gaz_id"]
    if not _is_int(gid) or gid <= 0:
        raise ValueError(f"{where}.gaz_id must be a positive integer")
    where = f"gaz_id {gid}"
    name = _text(raw["canonical_name"], f"{where}.canonical_name", 200)
    ftype = raw["feature_type"]
    if ftype not in FEATURE_TYPES:
        raise ValueError(f"{where}.feature_type must be one of {FEATURE_TYPES}")
    forms = raw["surface_forms"]
    if not isinstance(forms, list) or not all(isinstance(f, str) and len(f) <= 200 for f in forms):
        raise ValueError(f"{where}.surface_forms must be a list of strings (at most 200 characters each)")
    lon, lat = raw["lon"], raw["lat"]
    if not (_is_num(lon) and _is_num(lat) and -180.0 <= lon <= 180.0 and -90.0 <= lat <= 90.0):
        raise ValueError(f"{where} lon/lat must be WGS84 degrees")
    jid, sid = raw["junction_id"], raw["segment_id"]
    for label, v in (("junction_id", jid), ("segment_id", sid)):
        if v is not None and (not _is_int(v) or v <= 0):
            raise ValueError(f"{where}.{label} must be a positive integer or null")
    if ftype == "junction" and jid is None:
        raise ValueError(f"{where}: a junction carries its junction_id")
    if ftype == "road" and sid is None:
        raise ValueError(f"{where}: a road carries its segment_id")
    imp = raw["importance"]
    if not (_is_num(imp) and 0.0 <= imp <= 1.0):
        raise ValueError(f"{where}.importance must be within 0..1")
    source = _text(raw["source"], f"{where}.source", 64)
    lang = raw["lang_primary"]
    if not isinstance(lang, str) or not _LANG.match(lang):
        raise ValueError(f"{where}.lang_primary must be a language code")
    return GazetteerEntry(
        gaz_id=gid,
        canonical_name=name,
        feature_type=ftype,
        surface_forms=tuple(forms),
        lon=float(lon),
        lat=float(lat),
        junction_id=jid,
        segment_id=sid,
        importance=float(imp),
        source=source,
        lang_primary=lang,
    )


def _indexable(form: str) -> bool:
    """A form the scanner may match: at least 3 characters and not made only of generic words."""
    return len(form) >= MIN_FORM_CHARS and not all(t in GENERIC_STOPWORDS for t in form.split(" "))


def _trigrams(s: str) -> frozenset[str]:
    p = f"  {s} "
    return frozenset(p[i : i + 3] for i in range(len(p) - 2))


def select_longest(hits: Iterable[Hit], tokens: Sequence[str], form_order: Mapping[str, int]) -> list[Hit]:
    """The PoC's greedy longest-match selection: hits ordered by covered length (characters, longest first), a
    verbatim gazetteer hit before a grammar rewrite of the same length, then the form's index order, then position;
    each taken unless it overlaps a token already taken. Returned in selection order."""

    def key(h: Hit) -> tuple[int, int, int, int]:
        covered = len(" ".join(tokens[h.start : h.end]))
        return (-covered, 0 if h.via == "gazetteer" else 1, form_order.get(h.form, 1 << 30), h.start)

    used = [False] * len(tokens)
    out: list[Hit] = []
    for h in sorted(set(hits), key=key):
        if any(used[h.start : h.end]):
            continue
        for k in range(h.start, h.end):
            used[k] = True
        out.append(h)
    return out


class Gazetteer:
    """The loaded X19 gazetteer: :attr:`entries`, :attr:`by_id`, :attr:`protect_set`, :meth:`norm`, and the
    longest-match index (:meth:`match`, :meth:`hits`, :meth:`lookup`, :meth:`fuzzy`). Immutable once built."""

    norm = staticmethod(norm)

    def __init__(self, entries: Sequence[GazetteerEntry], meta: Mapping[str, Any], path: Path | None = None) -> None:
        self.path = path
        self.meta: Mapping[str, Any] = MappingProxyType(dict(meta))
        self.entries: tuple[GazetteerEntry, ...] = tuple(sorted(entries, key=lambda e: e.gaz_id))
        by_id: dict[int, GazetteerEntry] = {}
        for e in self.entries:
            if e.gaz_id in by_id:
                raise ValueError(f"duplicate gaz_id {e.gaz_id}")
            by_id[e.gaz_id] = e
        self.by_id: Mapping[int, GazetteerEntry] = MappingProxyType(by_id)

        forms: dict[str, list[int]] = {}
        protect: set[str] = set()
        for e in self.entries:
            for name in (e.canonical_name, *_PARENS.split(e.canonical_name)):
                n = norm(name)
                if n:
                    protect.add(n)
            for raw in e.surface_forms:
                f = norm(raw)
                if not f:
                    continue
                protect.add(f)
                if _indexable(f):
                    ids = forms.setdefault(f, [])
                    if e.gaz_id not in ids:
                        ids.append(e.gaz_id)
        #: every normalised surface form, canonical name and parenthesised part (OS-2's place protect-set)
        self.protect_set: frozenset[str] = frozenset(protect)
        #: normalised form → the gaz_ids it names (index order: entries by gaz_id, then their forms)
        self.forms: Mapping[str, tuple[int, ...]] = MappingProxyType({f: tuple(v) for f, v in forms.items()})
        self.form_order: Mapping[str, int] = MappingProxyType({f: i for i, f in enumerate(forms)})

        trie: dict[str, Any] = {}
        for f in forms:
            node = trie
            for tok in f.split(" "):
                node = node.setdefault(tok, {})
            node[_END] = f
        self._trie = trie
        self.vocabulary: frozenset[str] = frozenset(t for f in forms for t in f.split(" "))

        # fuzzy pool: multi-word forms of at least 8 characters, trigram-indexed (the PoC's multi-word-only rule)
        pool = tuple(f for f in forms if " " in f and len(f) >= 8)
        grams: dict[str, list[int]] = {}
        sizes: list[int] = []
        for i, f in enumerate(pool):
            tg = _trigrams(f)
            sizes.append(len(tg))
            for g in tg:
                grams.setdefault(g, []).append(i)
        self._pool = pool
        self._pool_sizes = tuple(sizes)
        self._grams: Mapping[str, tuple[int, ...]] = MappingProxyType({g: tuple(v) for g, v in grams.items()})

    # ---------------------------------------------------------------- construction
    @classmethod
    def from_document(cls, doc: Any, path: Path | None = None) -> Gazetteer:
        """Validate an X19 document (places only) and build the gazetteer from it."""
        if not isinstance(doc, Mapping):
            raise ValueError("the gazetteer is a JSON object {meta, entries}")
        top_extra = sorted(str(k) for k in set(doc) - {"meta", "entries"})
        if top_extra:
            raise ValueError(f"unexpected top-level keys: {top_extra}")
        meta = doc.get("meta")
        if not isinstance(meta, Mapping):
            raise ValueError("meta must be an object")
        meta_extra = sorted(str(k) for k in set(meta) - set(META_FIELDS))
        if meta_extra:
            raise ValueError(f"meta has keys outside the X19 field list: {meta_extra}")
        raw_entries = doc.get("entries")
        if not isinstance(raw_entries, list):
            raise ValueError("entries must be a list")
        entries = [_entry(raw, i) for i, raw in enumerate(raw_entries)]
        if "entries" in meta and meta["entries"] != len(entries):
            raise ValueError(f"meta.entries says {meta['entries']}, the file has {len(entries)}")
        return cls(entries, meta, path)

    # ---------------------------------------------------------------- matching
    def tokens(self, text: str) -> list[str]:
        """``text`` in normal form, split into tokens; a Bengali word carrying a case ending ("বেহালায়") reads as
        its stem when the stem is a gazetteer word.

        An inflected word the gazetteer itself carries inside a longer form ("গড়িয়াহাটের", of Gariahat, in the
        junction alias "গড়িয়াহাটের মোড়") stays whole only where such a longer form matches; elsewhere it reads as
        its stem too ("গড়িয়াহাটের দোকানে আগুন" names the neighbourhood)."""
        toks = norm(text).split()
        vocab = self.vocabulary
        held: list[int] = []
        for i, t in enumerate(toks):
            if not translit.is_indic(t):
                continue
            if t in vocab:
                if t not in self.forms and self._stem(t) is not None:
                    held.append(i)
                continue
            stem = self._stem(t)
            if stem is not None:
                toks[i] = stem
        if held:
            inside = {k for h in self.hits(toks) if h.end - h.start > 1 for k in range(h.start, h.end)}
            for i in held:
                if i not in inside:
                    toks[i] = self._stem(toks[i]) or toks[i]
        return toks

    def _stem(self, token: str) -> str | None:
        """``token`` without its Bengali case ending, when what remains is a gazetteer word (the longest ending
        first)."""
        for suf in translit.BN_SUFFIXES:
            if token.endswith(suf) and len(token) > len(suf) and token[: -len(suf)] in self.vocabulary:
                return token[: -len(suf)]
        return None

    def hits(self, tokens: Sequence[str]) -> list[Hit]:
        """Every occurrence of every indexed form in ``tokens`` (overlapping; :func:`select_longest` chooses)."""
        out: list[Hit] = []
        trie = self._trie
        for i in range(len(tokens)):
            node = trie
            for j in range(i, len(tokens)):
                node = node.get(tokens[j])
                if node is None:
                    break
                form = node.get(_END)
                if form is not None:
                    out.append(Hit(i, j + 1, form))
        return out

    def match(self, text: str) -> list[Hit]:
        """The places ``text`` names exactly: the greedy longest-match selection over its tokens."""
        toks = self.tokens(text)
        return select_longest(self.hits(toks), toks, self.form_order)

    def lookup(self, form: str) -> tuple[int, ...]:
        """The gaz_ids an exact (normalised) surface form names, or ``()``."""
        return self.forms.get(norm(form), ())

    def fuzzy(
        self, window: str, cutoff: float = 0.90, exclude: Collection[str] = frozenset()
    ) -> tuple[str, float] | None:
        """The multi-word surface form closest to ``window`` by ``difflib`` ratio, if it reaches ``cutoff``.

        Candidates are pre-filtered by shared character trigrams (Dice ≥ 0.3: one edit costs at most three trigrams)
        and by length (a ratio ``c`` needs the shorter string to be at least ``c / (2 − c)`` of the longer: 0.818 at
        the resolver's 0.90); a form in ``exclude`` is never a candidate; ties go to the form earlier in the
        index."""
        if not 0.0 < cutoff <= 1.0:
            raise ValueError("cutoff must be within (0, 1]")
        w = norm(window)
        if not w:
            return None
        tg = _trigrams(w)
        counts: dict[int, int] = {}
        for g in tg:
            for i in self._grams.get(g, ()):
                counts[i] = counts.get(i, 0) + 1
        lo = cutoff / (2.0 - cutoff)
        best: tuple[float, int] | None = None
        for i, shared in counts.items():
            f = self._pool[i]
            if f in exclude or 2.0 * shared / (len(tg) + self._pool_sizes[i]) < 0.3:
                continue
            if not lo <= len(f) / len(w) <= 1.0 / lo:
                continue
            r = difflib.SequenceMatcher(None, w, f, autojunk=False).ratio()
            if r >= cutoff and (best is None or r > best[0] or (r == best[0] and i < best[1])):
                best = (r, i)
        return None if best is None else (self._pool[best[1]], best[0])

    # ---------------------------------------------------------------- access
    def __len__(self) -> int:
        return len(self.entries)

    def __iter__(self) -> Iterator[GazetteerEntry]:
        return iter(self.entries)

    def entry(self, gaz_id: int) -> GazetteerEntry:
        return self.by_id[gaz_id]


_CACHE: dict[str, Gazetteer] = {}
_LOCK = threading.Lock()


def load(path: str | os.PathLike[str] | None = None) -> Gazetteer:
    """The gazetteer at ``path`` (or by the path rules), validated, built once per process and cached by path.

    Raises ``FileNotFoundError`` when there is none and ``ValueError`` when it is not a valid X19 places file."""
    p = resolve_path(path, env=GAZETTEER_ENV, repo_relative=_REPO_RELATIVE, image=IMAGE_PATH)
    key = str(p.resolve())
    with _LOCK:
        cached = _CACHE.get(key)
        if cached is not None:
            return cached
        if p.stat().st_size > _MAX_BYTES:
            raise ValueError(f"{p} is larger than {_MAX_BYTES} bytes")
        gaz = Gazetteer.from_document(json.loads(p.read_text(encoding="utf-8")), path=p)
        _CACHE[key] = gaz
        return gaz


def clear_cache() -> None:
    """Forget every loaded gazetteer (tests, or after a regeneration in a long-lived process)."""
    with _LOCK:
        _CACHE.clear()
