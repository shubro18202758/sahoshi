NETWORK_ENV = "OSINT_NETWORK_PATH"
_REPO_RELATIVE = ("scripts", "data", "osm_network.json")
IMAGE_PATH = Path("/repo/VVIP/scripts/data/osm_network.json")
#: A point within this distance of a junction node is at the junction (``osm_network.json`` limits).
JUNCTION_TOL_M = 25.0
#: The reach (the PoC's 2.5 km): beyond it from every segment anchor and every road line, a place has no road anchor.
MAX_SNAP_M = 2500.0

#: The WGS84 ellipsoid every distance is measured on (pyproj; no PROJ grid or network access is needed).
GEOD = Geod(ellps="WGS84")
_MAX_BYTES = 32 * 1024 * 1024


def geodesic_m(lon1: float, lat1: float, lon2: float, lat2: float) -> float:
    """The WGS84 geodesic distance in metres (pyproj)."""
    return float(GEOD.inv(lon1, lat1, lon2, lat2)[2])


@dataclass(frozen=True, slots=True)
class Segment:
    """A ``corridor.road_segments`` row: its id, road name, class, stored line and network anchor."""

    segment_id: int
    road_name: str
    road_class: str | None
    line: tuple[tuple[float, float], ...]
    anchor: tuple[float, float]


@dataclass(frozen=True, slots=True)
class Junction:
    """A ``corridor.junctions`` row: its id, name and OSM node point."""

    junction_id: int
    name: str
    lon: float
    lat: float


class SnapResult(NamedTuple):
    """``(segment_id, junction_id, snapped_to, residual_m)``: what a point attaches to, and how far it is."""

    segment_id: int | None
    junction_id: int | None
    snapped_to: str | None
    residual_m: float | None


def _is_int(v: Any) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _lonlat(v: Any, where: str) -> tuple[float, float]:
    if not (isinstance(v, Sequence) and len(v) >= 2):
        raise ValueError(f"{where} is not a [lon, lat] pair")
    try:
        lon, lat = float(v[0]), float(v[1])
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{where} is not a [lon, lat] pair of numbers") from exc
    if not (math.isfinite(lon) and math.isfinite(lat) and -180 <= lon <= 180 and -90 <= lat <= 90):
        raise ValueError(f"{where} is not a WGS84 point")
    return (lon, lat)


class Network:
    """The road network (Kolkata's 65 segments and 49 junctions): :attr:`segments`, :attr:`junctions` and
    :meth:`snap`."""

    def __init__(self, segments: Sequence[Segment], junctions: Sequence[Junction], path: Path | None = None) -> None:
        if not segments:
            raise ValueError("a network has at least one segment")
        self.path = path
        self.segments: Mapping[int, Segment] = MappingProxyType({s.segment_id: s for s in segments})
        self.junctions: Mapping[int, Junction] = MappingProxyType({j.junction_id: j for j in junctions})
        if len(self.segments) != len(segments) or len(self.junctions) != len(junctions):
            raise ValueError("segment and junction ids are unique")
        pts = [s.anchor for s in segments] + [(j.lon, j.lat) for j in junctions]
        lat0 = sum(p[1] for p in pts) / len(pts)
        self._origin = (sum(p[0] for p in pts) / len(pts), lat0)
        # a local equirectangular plane in metres: only ranks candidates (exact distances are geodesic)
        self._kx = 111_320.0 * math.cos(math.radians(lat0))
        self._ky = 110_574.0
        self._seg_ids = tuple(s.segment_id for s in segments)
        self._seg_tree = STRtree([Point(self._xy(*s.anchor)) for s in segments])
        self._jct_ids = tuple(j.junction_id for j in junctions)
        self._jct_tree = STRtree([Point(self._xy(j.lon, j.lat)) for j in junctions]) if junctions else None
        self._lines_xy: Mapping[int, LineString] = MappingProxyType(
            {s.segment_id: LineString([self._xy(x, y) for x, y in s.line]) for s in segments}
        )
        self._line_tree = STRtree([self._lines_xy[sid] for sid in self._seg_ids])

    def _xy(self, lon: float, lat: float) -> tuple[float, float]:
        return ((lon - self._origin[0]) * self._kx, (lat - self._origin[1]) * self._ky)

    def _lonlat(self, x: float, y: float) -> tuple[float, float]:
        return (x / self._kx + self._origin[0], y / self._ky + self._origin[1])

    # ---------------------------------------------------------------- construction
    @classmethod
    def from_document(cls, doc: Any, path: Path | None = None) -> Network:
        """Build from an ``osm_network.json`` document (its ``segments`` and ``junctions``)."""
        if not isinstance(doc, Mapping):
            raise ValueError("the network is a JSON object with segments and junctions")
        segs: list[Segment] = []
        for i, s in enumerate(doc.get("segments") or []):
            sid = s.get("segment_id") if isinstance(s, Mapping) else None
            if not _is_int(sid) or sid <= 0:
                raise ValueError(f"segments[{i}].segment_id must be a positive integer")
            raw = s.get("line")
            if not isinstance(raw, list) or len(raw) < 2:
                raise ValueError(f"segment {sid} has no line")
            line = tuple(_lonlat(p, f"segment {sid} line") for p in raw)
            name = s.get("road_name")
            if not isinstance(name, str) or not name.strip():
                raise ValueError(f"segment {sid} has no road_name")
            rc = s.get("road_class")
            segs.append(Segment(sid, name, rc if isinstance(rc, str) else None, line, interior_point(line)))
        jcts: list[Junction] = []
        for i, j in enumerate(doc.get("junctions") or []):
            jid = j.get("junction_id") if isinstance(j, Mapping) else None
            if not _is_int(jid) or jid <= 0:
                raise ValueError(f"junctions[{i}].junction_id must be a positive integer")
            lon, lat = _lonlat((j.get("lon"), j.get("lat")), f"junction {jid}")
            name = j.get("name")
            if not isinstance(name, str) or not name.strip():
                raise ValueError(f"junction {jid} has no name")
            jcts.append(Junction(jid, name, lon, lat))
        return cls(segs, jcts, path)

    # ---------------------------------------------------------------- queries
    def _nearest(self, tree: STRtree, ids: tuple[int, ...], points: Sequence[tuple[float, float]],
                 lon: float, lat: float) -> tuple[int, float]:
        """The id whose point is geodesically nearest ``(lon, lat)``: the planar nearest from the STRtree, then
        every point within a margin of it re-measured on the ellipsoid (ties → the lower id)."""
        p = Point(self._xy(lon, lat))
        i0 = int(tree.nearest(p))
        d0 = float(tree.geometries[i0].distance(p))
        near = tree.query(p, predicate="dwithin", distance=d0 * 1.01 + 10.0)
        idx = np.unique(np.append(np.asarray(near, dtype=np.int64), i0))
        lons = np.array([points[k][0] for k in idx])
        lats = np.array([points[k][1] for k in idx])
        _, _, dist = GEOD.inv(np.full(len(idx), lon), np.full(len(idx), lat), lons, lats)
        best = min(zip(dist.tolist(), (ids[k] for k in idx), strict=True), key=lambda t: (t[0], t[1]))
        return best[1], best[0]

    def nearest_segment(self, lon: float, lat: float) -> tuple[Segment, float]:
        """The segment whose anchor is nearest, and the geodesic distance to that anchor in metres."""
        anchors = [self.segments[s].anchor for s in self._seg_ids]
        sid, d = self._nearest(self._seg_tree, self._seg_ids, anchors, lon, lat)
        return self.segments[sid], d

    def nearest_junction(self, lon: float, lat: float) -> tuple[Junction, float] | None:
        """The nearest junction node and its geodesic distance, or ``None`` for a network without junctions."""
        if self._jct_tree is None:
            return None
        pts = [(self.junctions[j].lon, self.junctions[j].lat) for j in self._jct_ids]
        jid, d = self._nearest(self._jct_tree, self._jct_ids, pts, lon, lat)
        return self.junctions[jid], d

    def line_distance_m(self, lon: float, lat: float, segment_id: int) -> float:
        """The geodesic distance from a point to the closest point of a segment's line (for display)."""
        line = self._lines_xy[segment_id]
        q = nearest_points(line, Point(self._xy(lon, lat)))[0]
        qlon, qlat = self._lonlat(q.x, q.y)
        return geodesic_m(lon, lat, qlon, qlat)

    def nearest_line(self, lon: float, lat: float) -> tuple[Segment, float]:
        """The segment whose road line passes nearest, and the geodesic distance to its closest point."""
        p = Point(self._xy(lon, lat))
        i0 = int(self._line_tree.nearest(p))
        d0 = float(self._line_tree.geometries[i0].distance(p))
        near = self._line_tree.query(p, predicate="dwithin", distance=d0 * 1.01 + 10.0)
        cands = {self._seg_ids[int(k)] for k in np.append(np.asarray(near, dtype=np.int64), i0)}
        sid, d = min(((s, self.line_distance_m(lon, lat, s)) for s in cands), key=lambda t: (t[1], t[0]))
        return self.segments[sid], d

    def snap(
        self, lon: float, lat: float, *, junction_tol_m: float = JUNCTION_TOL_M, max_m: float = MAX_SNAP_M
    ) -> SnapResult:
        """Attach a WGS84 point to the network (module docstring); the residual is rounded to 0.1 m."""
        if not (math.isfinite(lon) and math.isfinite(lat) and -180 <= lon <= 180 and -90 <= lat <= 90):
            raise ValueError("snap takes a WGS84 lon, lat")
        if junction_tol_m > 0:
            nj = self.nearest_junction(lon, lat)
            if nj is not None and nj[1] <= junction_tol_m:
                return SnapResult(None, nj[0].junction_id, nj[0].name, round(nj[1], 1))
        seg, d = self.nearest_segment(lon, lat)
        if d <= max_m:
            return SnapResult(seg.segment_id, None, seg.road_name, round(d, 1))
        # no anchor within reach: a road may still pass right by (a long segment's far end)
        line_seg, line_d = self.nearest_line(lon, lat)
        if line_d <= max_m:
            return SnapResult(line_seg.segment_id, None, line_seg.road_name, round(line_d, 1))
        return SnapResult(None, None, None, round(d, 1))


_CACHE: dict[str, Network] = {}
_LOCK = threading.Lock()


def load_network(path: str | os.PathLike[str] | None = None) -> Network:
    """The network at ``path`` (or by the path rules), built once per process and cached by path."""
    p = resolve_path(path, env=NETWORK_ENV, repo_relative=_REPO_RELATIVE, image=IMAGE_PATH, anchor=Path(__file__))
    key = str(p.resolve())
    with _LOCK:
        cached = _CACHE.get(key)
        if cached is not None:
            return cached
        if p.stat().st_size > _MAX_BYTES:
            raise ValueError(f"{p} is larger than {_MAX_BYTES} bytes")
        net = Network.from_document(json.loads(p.read_text(encoding="utf-8")), path=p)
        _CACHE[key] = net
        return net


def snap(
    lon: float,
    lat: float,
    *,
    network: Network | None = None,
    junction_tol_m: float = JUNCTION_TOL_M,
    max_m: float = MAX_SNAP_M,
) -> SnapResult:
    """Snap a point onto the network of record (``load_network()`` unless one is given): see the module docstring."""
    return (network or load_network()).snap(lon, lat, junction_tol_m=junction_tol_m, max_m=max_m)


def clear_cache() -> None:
    """Forget every loaded network (tests)."""
    with _LOCK:
        _CACHE.clear()
