"""The road network of record and the snap onto it (OSINT SPEC §1.4 step 5; research A7).

``scripts/data/osm_network.json`` (generated by ``scripts/gen_osm_network.py``; read only, never edited here) holds
Kolkata's 65 ``corridor.road_segments`` (ids 1001-1065, each with its stored OSM line) and 49
``corridor.junctions`` (ids 1-49, each an OSM node). Its path follows the gazetteer's rules: the argument, then
``$OSINT_NETWORK_PATH``, then the repo's ``scripts/data/osm_network.json`` walking up from this file, then
``/repo/VVIP/scripts/data/osm_network.json`` (the images).

**Where a segment is.** Each segment has one network anchor: ``ST_PointOnSurface`` of its line (GEOS
InteriorPointLine: the interior vertex nearest the line's length-weighted centroid; shapely's
``point_on_surface``). It is the point the oracle itself uses for a segment: the dossier, the anomaly pins and the
unit-dispatch ETA (``units/router.py`` ``_SQL_SEGMENT_POINTS``) all place segment ``n`` there. The gazetteer's road
entries carry it as their ``lon``/``lat``.

**The snap** (:func:`snap`, ``(segment_id | None, junction_id | None, snapped_to, residual_m)``):

* a point within ``junction_tol_m`` of a junction node (default 25 m, the network's own node tolerance
  ``limits.junction_node_max_m``) is AT that junction: ``(None, junction_id, name, distance)``;
* otherwise it attaches to the segment whose anchor is nearest, ``(segment_id, None, road_name, residual)``,
  where the residual is the geodesic distance (pyproj, WGS84) from the point to that anchor: how far the reported
  place is from where Sahoshi pins the segment and sends units;
* when no anchor is within ``max_m`` (2.5 km, the PoC's reach) but a road passes within it — a place near the end
  of a long segment — it attaches to the nearest road line, the residual then
  being the distance to that line;
* otherwise there is no road anchor: ``(None, None, None, distance to the nearest anchor)``.

The resolver keeps a junction toponym's own ``junction_id`` and snaps landmarks and neighbourhoods to the nearest
segment (``junction_tol_m=0``), as the WP rules. This is the PoC's snap (Eden Gardens attaches to Sahid Khudiram Bose
Road 1012 at 210.1 m) made exact: the PoC used the vertex nearest the vertex mean as a stand-in for the segment's point;
here it is the oracle's own ``ST_PointOnSurface``. :meth:`Network.line_distance_m` gives the distance to the road
line itself for display ("the road passes 156 m away"). Known limit, kept for the PoC calibration (plan R23): on a
long segment the anchor can be farther than another segment's, so a place beside a road may attach to a shorter
neighbour with a larger residual (its snap quality then says so).

Nearest-geometry queries use shapely ``STRtree`` over a local metric plane, refined by exact geodesic distances,
so near-ties are decided by the true distance (then by the lower id). Loaded once per process and immutable
afterwards (thread-safe for reads).
"""

