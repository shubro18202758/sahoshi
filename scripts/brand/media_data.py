#!/usr/bin/env python3
"""Write the deck's photo and mark registries from the curated manifests (pure stdlib, deterministic).

  scripts/brand/photos/manifest.json  →  services/command-deck/src/lib/v3/media/photos.data.ts
  scripts/brand/logos/manifest.json   →  services/command-deck/src/lib/v3/media/logos.data.ts

The manifests carry each file's source, author, licence and notes (static/photos/NOTICE.md and static/logos/NOTICE.md
are their human-readable twins). A photo of a generic subject (a taxi, a tram, a pandal) is never matched to an event
by distance: `near` is forced false for those place keys.

Run:  python3 scripts/brand/media_data.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MEDIA = os.path.join(HERE, '..', '..', 'services', 'command-deck', 'src', 'lib', 'v3', 'media')
GENERIC = {'taxi', 'tram', 'ferry', 'metro', 'pandal', 'waterlogging'}


def js(v):
    return json.dumps(v, ensure_ascii=False)


def num(v):
    return f'{v:g}' if isinstance(v, (int, float)) else js(v)


def photos():
    rows = json.load(open(os.path.join(HERE, 'photos', 'manifest.json'), encoding='utf-8'))
    out = ['/**',
           ' * Reference photographs of Kolkata (Wikimedia Commons; each under its own licence — static/photos/NOTICE.md).',
           ' * Generated by scripts/brand/media_data.py from scripts/brand/photos/manifest.json; do not edit by hand. Photos with a',
           ' * face, a person as the subject, a legible number plate or a political poster were left out when the set was curated.',
           ' * `near` is false for generic subjects (a taxi, a tram, a ferry, a metro train, a pandal, a waterlogged street): those',
           ' * illustrate a kind of thing, never a place, so they are never matched to an event by distance.',
           ' */',
           "import type { PlacePhoto } from './photos';",
           '',
           'export const PHOTO_ROWS: readonly PlacePhoto[] = [']
    for p in rows:
        near = bool(p.get('near')) and p['place_key'] not in GENERIC
        out.append('\t{ ' + ', '.join([
            f'slug: {js(p["slug"])}', f'title: {js(p["title"])}', f'place: {js(p["place_key"])}',
            f'lat: {num(p["lat"])}', f'lon: {num(p["lon"])}', f'near: {"true" if near else "false"}',
            f'author: {js(p["author"])}', f'license: {js(p["license_short"])}', f'licenseUrl: {js(p["license_url"])}',
            f'source: {js(p["source_page_url"])}', f'credit: {js(p["attribution_text"])}']) + ' },')
    out.append('];')
    with open(os.path.join(MEDIA, 'photos.data.ts'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    return len(rows)


def marks():
    rows = json.load(open(os.path.join(HERE, 'logos', 'manifest.json'), encoding='utf-8'))
    out = ['/**',
           ' * The agency and source marks on file (static/logos). Generated by scripts/brand/media_data.py from',
           ' * scripts/brand/logos/manifest.json; do not edit by hand. Keys are the agency ids of cities/kolkata/city.json. Used',
           " * as-is: trimmed and resized only. `plate`: 'light' for a dark or transparent mark that needs a white plate on a dark",
           " * ground; 'dark' for a white mark that needs a dark plate on a light ground; 'none' for a mark that reads on both.",
           ' */',
           "import type { Mark } from './logos';",
           '',
           'export const MARK_ROWS: readonly Mark[] = [']
    for m in rows:
        w, h = round(float(m['w']), 2), round(float(m['h']), 2)
        out.append('\t{ ' + ', '.join([f"key: {js(m['key'])}", f"name: {js(m['name'])}", f"src: {js('/logos/' + m['file'])}",
                                        f'w: {w:g}', f'h: {h:g}', f"plate: {js(m['plate'])}"]) + ' },')
    out.append('];')
    with open(os.path.join(MEDIA, 'logos.data.ts'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    return len(rows)


if __name__ == '__main__':
    print('ok', photos(), 'photos,', marks(), 'marks')
